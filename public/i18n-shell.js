// Mixed labels can share an element with an icon, a form control or a live count.
// Keep references to the original text nodes so a render or a new chat can replace
// them without letting later language switches overwrite app or user content.
export function collectShellText(root) {
  const markers = root.createTreeWalker(root, 128); // NodeFilter.SHOW_COMMENT
  const labels = [];
  while (markers.nextNode()) {
    const comment = markers.currentNode;
    const node = comment.nextSibling;
    if (!comment.data.startsWith('i18n:shell.') || node?.nodeType !== 3) continue;
    const japanese = node.data.trim();
    const leading = node.data.slice(0, node.data.indexOf(japanese));
    const trailing = node.data.slice(leading.length + japanese.length);
    labels.push({ node, key: comment.data.slice(5), japanese, leading, trailing, last: node.data });
  }
  return labels;
}

export function renderShellText(labels) {
  for (const label of labels) {
    if (!label.node.isConnected || label.node.data !== label.last) continue;
    const text = t(label.key, label.japanese);
    // Keep intentional spacing between inline controls. Sentence punctuation
    // follows the preceding word directly in English.
    const leading = getLocale() === 'en' && text === '.' ? '' : label.leading;
    label.last = leading + text + label.trailing;
    label.node.data = label.last;
  }
}

export function bindLanguageControls(root) {
  const labels = collectShellText(root);
  const selectors = root.querySelectorAll('[data-ui-language]');
  const description = root.querySelector('meta[name="description"]');
  const originalDescription = description?.content;
  function render() {
    applyTranslations(root);
    renderShellText(labels);
    if (description) description.content = t('shell.description', originalDescription);
    for (const select of selectors) {
      select.value = getLocale();
      const status = root.getElementById(select.id + '-status');
      if (status) status.textContent = '';
    }
  }
  for (const select of selectors) {
    select.addEventListener('change', async () => {
      try {
        await setLocale(select.value);
      } catch {
        const status = root.getElementById(select.id + '-status');
        if (status) status.textContent = t('shell.languageSaveFailed', '言語の設定を保存できませんでした。もう一度選んでください。');
      } finally {
        select.value = getLocale();
      }
    });
  }
  onLocaleChange(render);
  render();
}

if (typeof document !== 'undefined') bindLanguageControls(document);
