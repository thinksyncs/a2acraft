export function projectText(message, values) {
  return t('projects.' + message, message, values);
}

// Mark a text leaf, so switching languages cannot replace a nested form field.
export function projectLabel(message) { return {projectLabel: message}; }
export function writeProjectLabel(node, value) {
  if (value?.projectLabel) {
    const span = document.createElement('span');
    span.setAttribute('data-i18n', 'projects.' + value.projectLabel);
    span.textContent = projectText(value.projectLabel);
    node.append(span);
  } else if (value !== undefined) node.textContent = value;
}
