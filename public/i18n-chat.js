registerMessages('en', Object.fromEntries(Object.entries(english).map(([source, en]) => ['chat.' + source, en])));

export function chatText(source, params) {
  if (typeof source !== 'string' || !source) return '';
  return Object.hasOwn(english, source) ? t('chat.' + source, source, params) : source;
}

export function messageCount(count) {
  return count === 1 ? chatText('1件のメッセージ') : chatText('{count}件のメッセージ', {count});
}

export function chatError(reason) {
  if (typeof reason !== 'string' || !reason) return '';
  const suffix=' 指示は送信していません。';
  if (reason.endsWith(suffix)) {
    const message=reason.slice(0,-suffix.length);
    if (Object.hasOwn(english,message)) return chatText(message) + chatText(suffix);
  }
  const match = /^残枠が(\d+(?:\.\d+)?)%以下のため、新規送信を停止しています。$/.exec(reason);
  return match ? chatText('残枠が{reserve}%以下のため、新規送信を停止しています。', {reserve:match[1]}) : chatText(reason);
}

/** Refresh only text supplied by a fictional sample. User edits, new messages
 * and task progress remain in place when switching languages mid-session. */
export function refreshSampleCopy(current, previous, next) {
  if (!current || typeof current !== 'object' || !previous || !next) return;
  if (Array.isArray(previous)) {
    if (!Array.isArray(current) || !Array.isArray(next)) return;
    const oldRows = new Map(previous.filter(row => row?.id).map(row => [row.id, row]));
    const newRows = new Map(next.filter(row => row?.id).map(row => [row.id, row]));
    for (const [index, row] of current.entries()) {
      if (oldRows.has(row?.id)) refreshSampleCopy(row, oldRows.get(row.id), newRows.get(row.id));
      else if (typeof row === 'string' && row === previous[index] && typeof next[index] === 'string') current[index] = next[index];
    }
    return;
  }
  for (const [key, value] of Object.entries(previous)) {
    if (typeof value === 'string' && typeof next[key] === 'string' && current[key] === value && next[key] !== value) current[key] = next[key];
    else if (value && typeof value === 'object') refreshSampleCopy(current[key], value, next[key]);
  }
}
