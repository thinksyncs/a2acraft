// Only the caller's UI template is looked up. Values supplied by a chat, quest or model are interpolated verbatim.
export function worldText(label, values) { return t(keyFor(label), label, values); }
export function worldBinding(label) { return {worldLabel:label}; }
export function setWorldLabel(node, label, attribute) {
  const marker = attribute ? 'data-i18n-' + attribute : 'data-i18n';
  node.setAttribute(marker, keyFor(label));
  if (attribute) node.setAttribute(attribute, worldText(label));
  else node.textContent = worldText(label);
  return node;
}
