export function translateInterfaceMarkup(root) {
  const walker = root.ownerDocument.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let text = walker.nextNode(); text; text = walker.nextNode()) {
    const key = text.data.trim();
    if (Object.hasOwn(english, key)) text.data = text.data.replace(key, () => english[key]);
  }
  for (const element of root.querySelectorAll('[aria-label], [placeholder], [title], [alt]')) {
    for (const attribute of ['aria-label', 'placeholder', 'title', 'alt']) {
      const key = element.getAttribute(attribute);
      if (Object.hasOwn(english, key)) element.setAttribute(attribute, english[key]);
    }
  }
}
